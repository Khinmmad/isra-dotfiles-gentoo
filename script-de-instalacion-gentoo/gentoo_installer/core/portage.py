def set_profile(root: Path, profile: str) -> bool:
    """Set Gentoo profile using eselect"""
    from . import chroot

    logger.info(f"Setting profile: {profile}")
    result = chroot.eselect_in_chroot(root, "profile", f"set {profile}")

    if result.ok:
        logger.info(f"Profile set to {profile}")
        return True
    else:
        logger.error(f"Failed to set profile: {result.stderr}")
        return False


def list_profiles(root: Path) -> list[str]:
    """List available Gentoo profiles"""
    from . import chroot

    result = chroot.eselect_in_chroot(root, "profile", "list")
    if result.ok:
        return result.stdout.strip().splitlines()
    return []


def sync_portage(root: Path) -> bool:
    """Sync portage tree"""
    from . import chroot

    logger.info("Syncing portage tree")
    result = chroot.chroot_run(root, "emerge --sync")

    if result.ok:
        logger.info("Portage tree synced")
        return True
    else:
        logger.error(f"Failed to sync portage: {result.stderr}")
        return False


def emerge(root: Path, packages: list[str], flags: str = "", verbose: bool = True) -> bool:
    """
    Emerge packages
    packages: list of package atoms
    flags: additional emerge flags
    """
    from . import chroot

    if not packages:
        logger.info("No packages to emerge")
        return True

    logger.info(f"Emerging: {' '.join(packages)}")

    # Build emerge command
    cmd_parts = ["emerge", "--ask=n"]
    if verbose:
        cmd_parts.append("--verbose")
    if flags:
        cmd_parts.append(flags)
    cmd_parts.extend(packages)

    cmd = " ".join(cmd_parts)
    result = chroot.chroot_run(root, cmd, timeout=None)

    if result.ok:
        logger.info(f"Successfully emerged: {' '.join(packages)}")
        return True
    else:
        logger.error(f"Failed to emerge packages: {result.stderr[-500:]}")
        return False


def setup_repositories(root: Path, overlays: list[str]) -> bool:
    """
    Setup overlays using eselect-repository
    overlays: list of overlay names (guru, hyproverlay, etc.)
    """
    from . import chroot

    for overlay in overlays:
        logger.info(f"Setting up overlay: {overlay}")

        # Check if already exists
        check = chroot.chroot_run(root, f"eselect repository list 2>/dev/null | grep {overlay}")
        if check.ok and overlay in check.stdout:
            logger.info(f"Overlay {overlay} already exists")
            # Sync it
            chroot.chroot_run(root, f"emaint sync -r {overlay}")
            continue

        # Add overlay
        if overlay == "guru":
            cmd = f"eselect repository add guru git https://github.com/gentoo-mirror/guru"
        elif overlay == "hyproverlay":
            cmd = f"eselect repository add hyproverlay git https://codeberg.org/hyprland-overlay/hyprland-overlay.git"
        else:
            cmd = f"eselect repository add {overlay}"

        result = chroot.chroot_run(root, cmd)
        if not result.ok:
            logger.warning(f"Failed to add overlay {overlay}: {result.stderr}")
            continue

        # Sync
        chroot.chroot_run(root, f"emaint sync -r {overlay}")
        logger.info(f"Overlay {overlay} added and synced")

    return True


def accept_keywords(root: Path, packages: list[str]) -> bool:
    """Accept ~amd64 keywords for packages"""
    root = Path(root)
    ak_file = root / "etc/portage/package.accept_keywords/custom"
    ak_file.parent.mkdir(parents=True, exist_ok=True)

    try:
        with open(ak_file, "a") as f:
            f.write("\n# Additional keywords\n")
            for pkg in packages:
                f.write(f"{pkg} ~amd64\n")
        return True
    except IOError as e:
        logger.error(f"Error writing keywords: {e}")
        return False


def setup_base_system(root: Path) -> bool:
    """Install base system packages"""
    base_packages = [
        "sys-kernel/linux-firmware",
        "sys-firmware/intel-microcode",
        "sys-firmware/amd-ucode",
        "net-misc/dhcpcd",
        "net-misc/openssh",
        "sys-process/htop",
        "app-editors/vim",
        "app-shells/zsh",
        "sys-auth/sudo",
        "sys-apps/mlocate",
        "sys-apps/pciutils",
        "sys-apps/usbutils",
    ]

    return emerge(root, base_packages)
