logger = logging.getLogger("gentoo-installer")


def configure_make_conf(root: Path, config: dict) -> bool:
    """
    Write /etc/portage/make.conf
    CFLAGS, CXXFLAGS, MAKEOPTS, USE, VIDEO_CARDS, GRUB_PLATFORMS
    """
    root = Path(root)
    make_conf = root / "etc/portage/make.conf"
    make_conf.parent.mkdir(parents=True, exist_ok=True)

    nproc = os.cpu_count() or 4
    cflags = "-march=native -O2 -pipe"
    cxxflags = cflags

    use_flags = config.get("use_flags_global", "")
    use_flags_list = [
        "systemd",
        "wayland",
        "pipewire",
        "pulseaudio",
        "bluetooth",
        "elogind",
        "udev",
        "dbus",
        "policykit",
        "X",
        "vulkan",
        "drm",
        "gbm",
    ]

    # Remove systemd if using OpenRC
    if config.get("init_system", "openrc") == "openrc":
        use_flags_list = [f for f in use_flags_list if f != "systemd"]
        use_flags_list.append("-systemd")

    # Add per-package USE flags
    use_flags_str = " ".join(use_flags_list)
    if use_flags:
        use_flags_str += f" {use_flags}"

    video_cards = config.get("video_cards", "")
    grub_platforms = config.get("grub_platforms", "efi-64")

    content = f"""# Generated by Gentoo Installer
# https://wiki.gentoo.org/wiki/Handbook:AMD64/Working/USE

CFLAGS="{cflags}"
CXXFLAGS="${{CFLAGS}}"

# Parallel jobs
MAKEOPTS="-j{nproc}"

# CPU features
CPU_FLAGS_X86="mmx mmxext sse sse2 sse3 ssse3 sse4_1 sse4_2 avx avx2 fma3"

# USE flags
USE="{use_flags_str}"

# Video cards
VIDEO_CARDS="{video_cards}"

# Bootloader
GRUB_PLATFORMS="{grub_platforms}"

# Accept license
ACCEPT_LICENSE="* -@EULA"

# Portage features
FEATURES="parallel-install parallel-fetch"

# emerge default options
EMERGE_DEFAULT_OPTS="--jobs={nproc} --load-average={nproc}"
"""

    try:
        with open(make_conf, "w") as f:
            f.write(content)
        logger.info(f"Written {make_conf}")
        return True

    except IOError as e:
        logger.error(f"Error writing make.conf: {e}")
        return False


def write_package_use(root: Path, use_flags: dict[str, str]) -> bool:
    """Write per-package USE flags to /etc/portage/package.use/custom"""
    root = Path(root)
    pkg_use = root / "etc/portage/package.use/custom"
    pkg_use.parent.mkdir(parents=True, exist_ok=True)

    try:
        with open(pkg_use, "w") as f:
            f.write("# Generated by Gentoo Installer\n\n")
            for pkg, flags in use_flags.items():
                f.write(f"{pkg} {flags}\n")
        logger.info(f"Written {pkg_use}")
        return True

    except IOError as e:
        logger.error(f"Error writing package.use: {e}")
        return False


